  simde__m128i even =
      simde_mm_and_si128(simde_mm_mullo_epi16(a, simde_mm_and_si128(pow2, lo)), lo);
  simde__m128i odd = simde_mm_mullo_epi16(simde_mm_andnot_si128(lo, a), simde_mm_srli_epi16(pow2, 8));
